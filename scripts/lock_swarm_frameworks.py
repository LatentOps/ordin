"""Lock an installed, tested Linux Python 3.12 SDK closure using primary PyPI hashes."""

import argparse
from concurrent.futures import ThreadPoolExecutor
from importlib.metadata import distribution
import json
from pathlib import Path
import re
from typing import cast
from urllib.parse import quote
from urllib.request import urlopen

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

ROOTS = {
    "langgraph": ("langgraph==1.2.20", "langgraph-prebuilt==1.1.1", "langchain-core==1.7.6"),
    "autogen": ("autogen-core==0.7.5",),
}


def closure(framework):
    environment = cast(dict[str, str], dict(default_environment()))
    if environment["python_version"] != "3.12" or environment["sys_platform"] != "linux":
        raise ValueError("generate locks in the tested Linux Python 3.12 environment")
    pending = [Requirement(v) for v in (*ROOTS[framework], "pydantic==2.14.2", "pytest==9.2.0")]
    selected: dict[str, str] = {}
    extras: dict[str, set[str]] = {}
    while pending:
        requested = pending.pop()
        name = canonicalize_name(requested.name)
        if requested.url or not re.fullmatch(r"[a-z0-9][a-z0-9._-]*", name):
            raise ValueError("only named PyPI distributions are supported")
        package = distribution(name)
        version = str(Version(package.version))
        if version not in requested.specifier:
            raise ValueError("installed dependency contract mismatch: " + name)
        wanted = {"", *requested.extras}
        previous = extras.get(name, set())
        if name in selected and wanted <= previous:
            continue
        selected[name], extras[name] = version, previous | wanted
        for raw in package.requires or ():
            child = Requirement(raw)
            if child.marker is None or any(
                child.marker.evaluate({**environment, "extra": value}) for value in extras[name]
            ):
                pending.append(child)
    return selected


def release_hashes(item):
    name, version = item
    address = (
        "https://pypi.org/pypi/" + quote(name, safe="") + "/" + quote(version, safe="") + "/json"
    )
    with urlopen(address, timeout=30) as response:
        packet = json.load(response)
    hashes = sorted({v["digests"]["sha256"] for v in packet["urls"] if not v.get("yanked")})
    if not hashes or any(not re.fullmatch(r"[a-f0-9]{64}", value) for value in hashes):
        raise ValueError("valid release artifact hashes unavailable: " + name)
    return name, version, hashes


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--framework", choices=(*ROOTS, "all"), default="all")
    parser.add_argument("--output-dir", type=Path, required=True)
    arguments = parser.parse_args()
    arguments.output_dir.mkdir(parents=True, exist_ok=True)
    for framework in ROOTS if arguments.framework == "all" else (arguments.framework,):
        with ThreadPoolExecutor(max_workers=4) as workers:
            releases = list(workers.map(release_hashes, sorted(closure(framework).items())))
        lines = [
            "# Generated by scripts/lock_swarm_frameworks.py after real SDK conformance.",
            "# Linux CPython 3.12; primary PyPI SHA-256 artifacts; no model downloads.",
        ]
        for name, version, hashes in releases:
            lines.append(name + "==" + version + " " + chr(92))
            lines.extend(
                "    --hash=sha256:" + value + (" " + chr(92) if index + 1 < len(hashes) else "")
                for index, value in enumerate(hashes)
            )
        path = arguments.output_dir / ("swarm-" + framework + ".txt")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(framework + ": " + str(len(releases)) + " pinned distributions")


if __name__ == "__main__":
    main()
